package dev.nicodiprospero.glyphwave.preview

import dev.nicodiprospero.glyphwave.glyph.CircleMask
import java.io.File
import java.util.Locale

/** Writes Android vector drawables from a matrix frame (toy preview + launcher foreground). */
object VectorDrawables {

    /**
     * Glyph Toy preview following the kit's Phone (3) icon spec: 512×512, black disc,
     * LED cells 13.05 units on a 17.82 pitch starting at 35.63; unlit LEDs #1C1C1C, lit #FFFFFF.
     */
    fun toyPreview(frame: IntArray, mask: CircleMask, file: File) {
        val n = mask.length
        val sb = StringBuilder()
        sb.appendLine("""<?xml version="1.0" encoding="utf-8"?>""")
        sb.appendLine("<!-- Generated by :core:renderPreviews (VectorDrawables.toyPreview). Do not edit by hand. -->")
        sb.appendLine("""<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="512dp" android:height="512dp" android:viewportWidth="512" android:viewportHeight="512">""")
        sb.appendLine("""  <path android:pathData="M256,256m-256,0a256,256 0,1 1,512 0a256,256 0,1 1,-512 0" android:fillColor="#000000"/>""")
        val lit = StringBuilder()
        val dark = StringBuilder()
        for (y in 0 until n) for (x in 0 until n) {
            if (!mask.contains(x, y)) continue
            val px = 35.63f + x * 17.82f
            val py = 35.63f + y * 17.82f
            val rect = "M%.2f,%.2fh13.05v13.05h-13.05z".format(Locale.US, px, py)
            (if (frame[y * n + x] > 0) lit else dark).append(rect)
        }
        sb.appendLine("""  <path android:pathData="$dark" android:fillColor="#1C1C1C"/>""")
        sb.appendLine("""  <path android:pathData="$lit" android:fillColor="#FFFFFF"/>""")
        sb.appendLine("</vector>")
        file.parentFile.mkdirs()
        file.writeText(sb.toString())
    }

    /** Adaptive-icon foreground (108dp, content inside the 66dp safe zone): lit LEDs as dots, centre LED in red. */
    fun launcherForeground(frame: IntArray, mask: CircleMask, file: File) {
        val n = mask.length
        val pitch = 58f / n
        val origin = (108f - pitch * n) / 2f
        val r = pitch * 0.42f
        val white = StringBuilder()
        val red = StringBuilder()
        val c = n / 2
        for (y in 0 until n) for (x in 0 until n) {
            if (!mask.contains(x, y) || frame[y * n + x] <= 0) continue
            val cx = origin + (x + 0.5f) * pitch
            val cy = origin + (y + 0.5f) * pitch
            val circle = "M%.3f,%.3fm-%.3f,0a%.3f,%.3f 0,1 1,%.3f 0a%.3f,%.3f 0,1 1,-%.3f 0"
                .format(Locale.US, cx, cy, r, r, r, 2 * r, r, r, 2 * r)
            val isCentre = x == c && y == c
            (if (isCentre) red else white).append(circle)
        }
        file.parentFile.mkdirs()
        file.writeText(
            """
            |<?xml version="1.0" encoding="utf-8"?>
            |<!-- Generated by :core:renderPreviews (VectorDrawables.launcherForeground). Do not edit by hand. -->
            |<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
            |  <path android:pathData="$white" android:fillColor="#FFFFFF"/>
            |  <path android:pathData="$red" android:fillColor="#D71921"/>
            |</vector>
            |""".trimMargin(),
        )
    }
}
